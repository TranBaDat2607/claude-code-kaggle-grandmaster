def log(msg):
    msg = str(msg).encode("ascii", "replace").decode("ascii")  # input file names can be anything
    print("[kg %6.1fm] %s" % ((time.time() - T0) / 60, msg), flush=True)


# ----------------------------------------------------------------------------- inputs
# Older Kaggle images mount each input as /kaggle/input/<slug>; newer ones in a folder per kind (and owner):
# /kaggle/input/competitions/<slug>, /kaggle/input/datasets/<owner>/<slug>.
KIND_DIRS = {"competition": ("competitions",), "dataset": ("datasets",), "kernel": ("notebooks", "kernels", "code")}
NOT_FOUND_HINT = {"kernel": " (a kernel's inputs are bound when it is pushed: was that kernel still running then?)",
                  "dataset": " (`gpu push` prints the inputs Kaggle could not attach)"}


def scan_inputs(refs, max_depth=4):
    """{slug: [(folder, names of the folders above it)]} for the folders under INPUT named like the slug of one
    of ``refs`` (any case), in a stable order. One walk for every source. It does not enter a source's folder
    (its data can be a large tree) unless the name is also an owner's or a kind's folder."""
    names = {r.strip("/").split("/")[-1].lower() for r in refs}
    walk_into = {r.strip("/").split("/")[0].lower() for r in refs if "/" in r.strip("/")}
    walk_into.update(d for dirs in KIND_DIRS.values() for d in dirs)
    found, frontier = {}, [(INPUT, ())]
    for _ in range(max_depth):
        nxt = []
        for d, above in frontier:
            try:
                kids = sorted(k for k in d.iterdir() if k.is_dir())
            except OSError:
                continue
            for k in kids:
                low = k.name.lower()
                if low in names:
                    found.setdefault(low, []).append((k, above))
                if low not in names or low in walk_into:
                    nxt.append((k, above + (low,)))
        frontier = nxt
    return found


def find_source(found, ref, kind=None):
    """The folder of ``ref`` (owner/slug, or a competition's slug) among those named like its slug: the one in a
    folder named like its owner (two owners can publish the same slug), then one under its kind's folder, then
    the shallowest."""
    parts = ref.strip("/").lower().split("/")
    owner = parts[0] if len(parts) > 1 else None
    kinds = KIND_DIRS.get(kind, ())

    def rank(c):
        return (owner is not None and c[1][-1:] == (owner,), any(a in kinds for a in c[1]), -len(c[1]))

    cands = found.get(parts[-1], [])
    return max(cands, key=rank)[0] if cands else None


def link(src, dst):
    """Symlink (Kaggle/Linux); copy when symlinks are unavailable (Windows test runs)."""
    if dst.exists() or dst.is_symlink():
        return False
    try:
        os.symlink(str(src), str(dst), target_is_directory=src.is_dir())
    except (OSError, NotImplementedError):
        if src.is_dir():
            shutil.copytree(str(src), str(dst))
        else:
            shutil.copy2(str(src), str(dst))
    return True


def make_folder(dest, ref, taken):
    """Make ``dest`` (and the folders above it) under RUN for the input of ``ref``. Returns why it cannot be made,
    or None: a folder linked from another input is that input's (read-only on Kaggle)."""
    parts = dest.split("/")
    for i in range(1, len(parts) + 1):
        rel = "/".join(parts[:i])
        p, held = RUN / rel, taken.get(rel, "")
        if held.startswith("linked") or p.is_symlink() or (p.exists() and not p.is_dir()):
            return "%s is already %s" % (rel, held or "a file")
        if not p.exists():
            p.mkdir()
            taken[rel] = "a folder for the input of %s" % ref
    return None


def link_inputs(sources, found, reserved=None):
    """Link the top-level entries of each source into its folder (``dest``: data, or a folder under it such as
    data/ext/<slug>). A name that is already taken there, or ``reserved`` ({path: what holds it}: the fold split,
    written after the inputs are linked), stays out with a warning saying what holds it: the first source keeps
    it. Returns one report row per source."""
    taken = {p.relative_to(RUN).as_posix(): "in the code bundle" for p in (RUN / "data").rglob("*")}
    taken.update(reserved or {})
    folder_of, rows = {}, []
    for s in sources:
        ref, kind, dest = s["ref"], s.get("kind"), s.get("dest") or "data"
        row = {"source": ref, "kind": kind, "dest": dest, "path": None, "linked": 0, "skipped": {}}
        rows.append(row)
        src = find_source(found, ref, kind)
        if src is None:
            row["error"] = "not found under %s" % INPUT
            log("WARNING: input %s not found under %s%s" % (ref, INPUT, NOT_FOUND_HINT.get(kind, "")))
            continue
        first = folder_of.setdefault(str(src.resolve()), ref)
        why = ("the only folder named like it, %s, is the input of %s" % (src, first) if first != ref
               else make_folder(dest, ref, taken))
        if why:
            row["error"] = why
            log("WARNING: input %s not linked: %s" % (ref, why))
            continue
        row["path"] = str(src)
        for k in sorted(src.iterdir()):
            rel = "%s/%s" % (dest, k.name)
            if rel in taken or not link(k, RUN / rel):
                row["skipped"][rel] = taken.get(rel, "there")
            else:
                taken[rel] = "linked from " + ref
                row["linked"] += 1
        log("linked %d entries of %s into %s/" % (row["linked"], src, dest))
        for rel, held in row["skipped"].items():
            log("WARNING: %s from %s skipped: already %s" % (rel, ref, held))
    return rows


def inputs_problem(rows):
    """One line on the inputs the run does not have, or None."""
    skipped = sum(len(r.get("skipped") or {}) for r in rows)
    lost = [r["source"] for r in rows if r.get("error")]
    if not (skipped or lost):
        return None
    msg = ["%d input entries were not linked, as the name was already taken (the first keeps it). Give each input "
           "its own folder: gpu build --input-layout nested (data/ext/<slug>/, kernel outputs data/ext/kout-<slug>/) "
           "or --dataset <owner>/<slug>=data/<folder>" % skipped] if skipped else []
    if lost:
        msg.append("inputs not linked or not found: %s" % ", ".join(lost))
    return "WARNING: " + "; ".join(msg)


def link_dir(dst, target):
    """Make dst a link to target (outputs are saved as they are written); returns False if it had to be a plain dir."""
    target.mkdir(parents=True, exist_ok=True)
    if dst.exists() or dst.is_symlink():
        return dst.resolve() == target.resolve()
    try:
        os.symlink(str(target), str(dst), target_is_directory=True)
        return True
    except (OSError, NotImplementedError):
        dst.mkdir(parents=True, exist_ok=True)
        return False


def copy_tree_missing(src, dst):
    n = 0
    for p in src.rglob("*"):
        if p.is_file():
            q = dst / p.relative_to(src)
            if not q.exists():
                q.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(str(p), str(q))
                n += 1
    return n


# ----------------------------------------------------------------------------- the fold split
def split_cells(rows):
    """Rows as the split's digest takes them (as `gpu build` took it): cells joined by \\x1f, rows ended by \\x1e."""
    return "".join("\x1f".join(r) + "\x1e" for r in rows).encode("utf-8")


def split_summary(split):
    how = ["%s: %s" % (name, "a range" if "range" in c else "%d values" % len(c["values"]) if "codes" in c
                       else "read from " + c["ref"] if "ref" in c else "text")
           for name, c in zip(split["header"], split["columns"])]
    return "%d rows; %s" % (split["rows"], ", ".join(how))


def read_column(path, name):
    """The cells of column ``name`` of the CSV at ``path``, row by row with blank lines skipped, as `gpu build` read
    them; '' for a row without it. ValueError when there is no such column."""
    with open(str(path), encoding="utf-8-sig", newline="") as f:
        rows = filter(None, csv.reader(f))
        i = next(rows, []).index(name)
        for r in rows:
            yield r[i] if i < len(r) else ""


def split_columns(split):
    """One iterator of cells per column of the packed split, and (name, file, iterator) of the columns read from a
    training file of this session."""
    n, cols, refs = split["rows"], [], []
    for name, c in zip(split["header"], split["columns"]):
        if "range" in c:
            start, step = c["range"]
            cols.append(map(str, range(start, start + step * n, step)))
        elif "codes" in c:
            cols.append(map(c["values"].__getitem__, (RUN / c["codes"]).read_bytes()))
        elif "text" in c:
            lines = (RUN / c["text"]).read_text(encoding="ascii").splitlines()
            cols.append(itertools.chain.from_iterable(json.loads(line) for line in lines))
        else:
            refs.append((name, c["ref"], read_column(RUN / c["ref"], name)))
            cols.append(refs[-1][2])
    return cols, refs


def write_split(split):
    """Write the fold split from its packed columns (`kgkit.gpu.pack_split`) and check its cells against the digest
    of yours. Returns why it could not, or None."""
    for name, c in zip(split["header"], split["columns"]):
        if "ref" in c and not (RUN / c["ref"]).is_file():
            return "its column %r is read from %s, which this session does not have" % (name, c["ref"])
    dst, n, count, why, refs, longer = RUN / split["file"], split["rows"], 0, None, [], []
    tmp = dst.with_name(dst.name + ".part")
    digest = hashlib.sha1(split_cells([split["header"]]))
    try:
        cols, refs = split_columns(split)
        with open(str(tmp), "w", encoding="utf-8", newline="") as f:
            w = csv.writer(f, lineterminator="\n")
            w.writerow(split["header"])
            rows = itertools.islice(zip(*cols), n)  # no column is read past the last row
            while True:
                batch = list(itertools.islice(rows, 1 << 16))
                if not batch:
                    break
                w.writerows(batch)
                digest.update(split_cells(batch))
                count += len(batch)
        longer = [ref for _, ref, it in refs if next(it, None) is not None]
    except (OSError, ValueError, UnicodeDecodeError, csv.Error) as e:
        why = "%s: %s" % (type(e).__name__, e)
    if why is None and count == n and not longer and digest.hexdigest() == split["digest"]:
        os.replace(str(tmp), str(dst))
        return None
    if tmp.exists():
        tmp.unlink()
    if refs:
        files = sorted({ref for _, ref, _ in refs})
        return ("its column(s) %s are read from %s, which in this session is not the file on your machine (%s). "
                "Rebuild once your %s is the session's (the competition's), or put data/folds.csv in a private dataset "
                "and build with --split-from <owner>/<slug>"
                % (", ".join(repr(name) for name, _, _ in refs), " and ".join(files),
                   why or ("fewer rows here" if count < n else "more rows here" if longer else "other values here"),
                   " and ".join(files)))
    return "the packed split does not give back your file (%s): a kgkit bug, please report it" % (why or "digest")


def file_sha1(path):
    h = hashlib.sha1()
    with open(str(path), "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def link_split(split, src):
    """Link the fold split from ``src``, the folder of the dataset given to --split-from: the file there with the
    size and sha1 of yours. Returns why it could not, or None."""
    if src is None:
        return "the dataset %s that holds it is not under %s%s" % (split["from"], INPUT, NOT_FOUND_HINT["dataset"])
    for p in sorted(src.rglob("*")):
        if p.is_file() and p.stat().st_size == split["bytes"] and file_sha1(p) == split["sha1"]:
            dst = RUN / split["file"]
            if dst.exists() or dst.is_symlink():  # a copy --include brought: this one is checked
                dst.unlink()
            link(p, dst)
            return None
    return ("the dataset %s has no copy of your %s (%d bytes, sha1 %s...): upload the current file as a new version "
            "of it" % (split["from"], split["file"], split["bytes"], split["sha1"][:12]))


def place_split(split, inputs):
    """Write or link ./data/folds.csv as the config says. Returns why it could not, or None."""
    if split.get("from"):
        row = next((r for r in inputs if r.get("use") == "split"), {})
        why = link_split(split, Path(row["path"]) if row.get("path") else None)
        how = "linked from the dataset %s (the same bytes as yours)" % split["from"]
    else:
        why = write_split(split)
        how = "written from the code bundle (%s), the same cells as yours" % split_summary(split)
    if why is None:
        log("%s %s" % (split["file"], how))
    return why


# ----------------------------------------------------------------------------- devices
def run_resource(cfg):
    if cfg.get("resource"):
        return cfg["resource"]
    acc = str(cfg.get("accelerator") or "").lower()
    return "TPU" if acc.startswith("tpu") else "CPU" if acc in ("none", "") else "GPU"


def list_tpu_chips(cfg):
    fake = os.environ.get("KG_FAKE_TPU_CHIPS")
    if fake is not None:
        n = int(fake)
    else:
        n = len([p for p in Path("/dev").glob("vfio/[0-9]*")]) or len(list(Path("/dev").glob("accel[0-9]*")))
        n = n or int(cfg.get("tpu_chips") or 0)
    return ["tpu-chip-%d" % i for i in range(n)]


def tpu_chip_env(env, chip):
    """One process per TPU chip (PJRT): the recipe's per-process batch stays what it was on one GPU."""
    port = 8476 + int(chip)
    env.update(PJRT_DEVICE="TPU", TPU_VISIBLE_CHIPS=str(chip), TPU_PROCESS_BOUNDS="1,1,1",
               TPU_CHIPS_PER_PROCESS_BOUNDS="1,1,1", TPU_PROCESS_PORT=str(port),
               TPU_PROCESS_ADDRESSES="localhost:%d" % port)
    return env


def list_gpus():
    fake = os.environ.get("KG_FAKE_GPUS")
    if fake is not None:
        return ["fake-gpu"] * int(fake)
    try:
        out = subprocess.run(["nvidia-smi", "--query-gpu=name,memory.total", "--format=csv,noheader"],
                             capture_output=True, text=True, timeout=30).stdout
        return [l.strip() for l in out.splitlines() if l.strip()]
    except (OSError, subprocess.SubprocessError):
        return []


class UtilSampler(threading.Thread):
    """Samples GPU utilisation; low mean utilisation means the run is input-bound (wasted quota)."""

    def __init__(self, interval):
        super().__init__(daemon=True)
        self.interval, self.samples, self.stop = interval, {}, threading.Event()

    def run(self):
        while not self.stop.wait(self.interval):
            try:
                out = subprocess.run(["nvidia-smi", "--query-gpu=index,utilization.gpu,memory.used",
                                      "--format=csv,noheader,nounits"], capture_output=True, text=True,
                                     timeout=20).stdout
            except (OSError, subprocess.SubprocessError):
                return
            for line in out.splitlines():
                parts = [p.strip() for p in line.split(",")]
                if len(parts) == 3 and parts[1].isdigit():
                    s = self.samples.setdefault(parts[0], {"util": [], "mem_mb": []})
                    s["util"].append(int(parts[1]))
                    s["mem_mb"].append(int(float(parts[2])))

    def summary(self):
        out = {}
        for idx, s in self.samples.items():
            if s["util"]:
                out[idx] = {"util_mean": round(sum(s["util"]) / len(s["util"]), 1),
                            "util_p10": sorted(s["util"])[len(s["util"]) // 10],
                            "mem_peak_mb": max(s["mem_mb"]), "n": len(s["util"])}
        return out


# ----------------------------------------------------------------------------- jobs
def stream(proc, logfile, prefix):
    with open(logfile, "a", encoding="utf-8", errors="replace") as f:
        for line in iter(proc.stdout.readline, ""):
            f.write(line)
            f.flush()
            sys.stdout.write(prefix + line.encode("ascii", "replace").decode("ascii"))
            sys.stdout.flush()


def run_cmd(cmd, env, logfile, prefix, hard_deadline):
    p = subprocess.Popen(cmd, shell=True, cwd=str(RUN), env=env, stdout=subprocess.PIPE,
                         stderr=subprocess.STDOUT, text=True, encoding="utf-8", errors="replace")
    t = threading.Thread(target=stream, args=(p, logfile, prefix), daemon=True)
    t.start()
    killed = False
    while p.poll() is None:
        if time.time() > hard_deadline:
            log("%s still running past the hard deadline: terminating so outputs are saved" % prefix.strip())
            p.terminate()
            try:
                p.wait(60)
            except subprocess.TimeoutExpired:
                p.kill()
            killed = True
            break
        time.sleep(2)
    t.join(30)
    return p.wait(), killed


def tail(path, n=40):
    try:
        return "".join(Path(path).read_text(encoding="utf-8", errors="replace").splitlines(True)[-n:])
    except OSError:
        return ""


def fold_done(art, f):
    st = art / ("fold%d_status.json" % f)
    if st.is_file():
        try:
            return json.loads(st.read_text(encoding="utf-8")).get("status") == "done"
        except ValueError:
            pass
    return (art / ("fold%d_oof.npy" % f)).is_file()


def fold_status(art, f, rc=None, killed=False):
    st = art / ("fold%d_status.json" % f)
    if st.is_file():
        try:
            return json.loads(st.read_text(encoding="utf-8"))
        except ValueError:
            pass
    if (art / ("fold%d_oof.npy" % f)).is_file():
        return {"fold": f, "status": "done"}
    if killed:
        return {"fold": f, "status": "killed"}
    if rc is None:
        return {"fold": f, "status": "not-started"}
    return {"fold": f, "status": "failed" if rc else "unknown", "returncode": rc}


# ----------------------------------------------------------------------------- main
def main():
    cfg = json.loads(base64.b64decode(CONFIG_B64).decode("utf-8"))
    jobs = cfg["jobs"]
    budget_s = float(cfg["hours"]) * 3600
    safety_s = max(600.0, 0.08 * budget_s)
    deadline = T0 + budget_s - safety_s              # training must have checkpointed by now
    hard_deadline = T0 + budget_s - 0.4 * safety_s   # processes still alive are terminated here
    resource = run_resource(cfg)
    tpu = resource == "TPU"
    devices = list_tpu_chips(cfg) if tpu else list_gpus()
    gpus = [] if tpu else devices
    log("jobs %s | accelerator %s | %s: %s | budget %.2fh (graceful stop at %.2fh)"
        % ([j["name"] for j in jobs], cfg.get("accelerator"), "tpu chips" if tpu else "gpus", devices or "NONE",
           budget_s / 3600, (deadline - T0) / 3600))
    if not devices and not cfg.get("allow_cpu"):
        log("WARNING: no %s visible - check the kernel accelerator setting; training on CPU" % resource)

    # 1. code + data
    if RUN.exists():
        shutil.rmtree(str(RUN))
    RUN.mkdir(parents=True)
    zipfile.ZipFile(io.BytesIO(base64.b64decode(PAYLOAD_B64))).extractall(str(RUN))
    (RUN / "data").mkdir(exist_ok=True)
    sources, resume, wheel_srcs = cfg.get("sources", []), cfg.get("resume_sources", []), cfg.get("wheel_sources", [])
    split = cfg.get("split")  # None: data/folds.csv is in the bundle as it is, or there is none
    split_srcs = [split["from"]] if split and split.get("from") else []
    found = scan_inputs([s["ref"] for s in sources] + resume + wheel_srcs + split_srcs)
    held = "taken by the fold split of %s" % split_srcs[0] if split_srcs else "in the code bundle"
    inputs = link_inputs(sources, found, {split["file"]: held} if split else None)
    for use, kind, refs in (("resume", "kernel", resume), ("wheels", "dataset", wheel_srcs),
                            ("split", "dataset", split_srcs)):
        for ref in refs:
            src = find_source(found, ref, kind)
            inputs.append({"source": ref, "kind": kind, "use": use, "path": str(src) if src else None})
            if src is None:
                inputs[-1]["error"] = "%s source not found under %s" % (use, INPUT)
                log("WARNING: %s source %s not found under %s%s" % (use, ref, INPUT, NOT_FOUND_HINT.get(kind, "")))
    inputs_note = inputs_problem(inputs)
    if inputs_note:
        log(inputs_note)
    why = place_split(split, inputs) if split else None
    if why:  # every result would be on another split than yours: nothing runs
        log("ERROR: %s not written: %s. Nothing was run." % (split["file"], why))
        sys.exit(1)
    OUT.mkdir(parents=True, exist_ok=True)
    live = {d: link_dir(RUN / d, OUT / d) for d in ("artifacts", "subs")}
    arts = {}
    resume_dirs = [Path(r["path"]) for r in inputs if r.get("use") == "resume" and r["path"]]
    for job in jobs:
        art = arts[job["name"]] = RUN / "artifacts" / job["name"]
        art.mkdir(parents=True, exist_ok=True)
        for src in resume_dirs:
            prev = src / "artifacts" / job["name"]
            if prev.is_dir():
                log("resume %s: copied %d files from %s" % (job["name"], copy_tree_missing(prev, art), prev))
            else:
                log("resume %s: %s has no artifacts/%s/" % (job["name"], src, job["name"]))
    if cfg.get("pip"):
        extra = []
        for r in inputs:
            if r.get("use") == "wheels" and r["path"]:
                extra += ["--no-index", "--find-links", r["path"]]
        log("pip install %s" % " ".join(cfg["pip"]))
        subprocess.run([sys.executable, "-m", "pip", "install", "-q", *extra, *cfg["pip"]], check=False)

    env = dict(os.environ, PYTHONPATH=os.pathsep.join([str(RUN), os.environ.get("PYTHONPATH", "")]),
               KGKIT_HOME=str(RUN), PYTHONUNBUFFERED="1", KG_DEADLINE=str(deadline),
               KG_RESERVE_S=str(cfg.get("reserve_s", 600)))
    prune = cfg.get("prune")
    if prune and (RUN / "_kg" / "baseline").is_dir():
        env.update(KG_PRUNE_BASELINE=str(RUN / "_kg" / "baseline"), KG_PRUNE_MARGIN=str(prune["margin"]),
                   KG_PRUNE_MIN_FRAC=str(prune.get("min_frac", 0.3)))
        log("pruning against %s (margin %s)" % (prune.get("baseline"), prune["margin"]))
    logs = OUT / "logs"
    logs.mkdir(exist_ok=True)
    sampler = UtilSampler(float(os.environ.get("KG_SAMPLE_S", "30")))
    if gpus and "KG_FAKE_GPUS" not in os.environ:
        sampler.start()

    # 2. tasks = (job, fold); one process per task, one task per GPU at a time. Interleaved by fold so
    #    two screens (or two folds of one job) keep both T4s busy.
    results = {}
    if len(jobs) == 1 and "{fold}" not in jobs[0]["cmd"]:  # a command that drives the GPUs itself (DDP)
        t = time.time()
        e = dict(env, PJRT_DEVICE="TPU") if tpu else env
        rc, killed = run_cmd(jobs[0]["cmd"], e, logs / "train.log", "[train] ", hard_deadline)
        results[(0, None)] = {"rc": rc, "killed": killed, "seconds": round(time.time() - t, 1)}
    else:
        todo = []
        for f in sorted({f for j in jobs for f in j["folds"]}):
            for ji, job in enumerate(jobs):
                if f in job["folds"]:
                    if fold_done(arts[job["name"]], f):
                        log("%s fold %d already done (resumed)" % (job["name"], f))
                    else:
                        todo.append((ji, f))
        lock = threading.Lock()

        def worker(slot):
            while True:
                with lock:
                    if not todo:
                        return
                    ji, f = todo.pop(0)
                job = jobs[ji]
                tag = "%s/f%d" % (job["name"], f)
                if time.time() > deadline - float(cfg.get("min_fold_start_s", 600)):
                    results[(ji, f)] = {"rc": None, "seconds": 0, "note": "not started: no time left"}
                    continue
                e = dict(env, KG_DEFER_ASSEMBLE="1")  # parallel folds must not race to log the experiment
                if tpu and devices:
                    tpu_chip_env(e, slot)
                elif gpus:
                    e["CUDA_VISIBLE_DEVICES"] = str(slot)
                cmd = job["cmd"].replace("{fold}", str(f))
                log("%s -> %s: %s" % (tag, ("tpu chip %s" if tpu else "gpu %s") % slot if devices else "cpu", cmd))
                t = time.time()
                rc, killed = run_cmd(cmd, e, logs / ("%s_fold%d.log" % (job["name"], f)), "[%s] " % tag,
                                     hard_deadline)
                results[(ji, f)] = {"rc": rc, "killed": killed, "seconds": round(time.time() - t, 1), "gpu": slot}
                log("%s finished rc=%s in %.1f min" % (tag, rc, (time.time() - t) / 60))

        n_workers = max(1, min(len(devices) or 1, len(todo) or 1))
        threads = [threading.Thread(target=worker, args=(i,)) for i in range(n_workers)]
        for t in threads:
            t.start()
        for t in threads:
            t.join()

    # 3. per-job status; assemble each job whose folds are all done
    job_reports = []
    for ji, job in enumerate(jobs):
        art, statuses = arts[job["name"]], {}
        for f in job["folds"]:
            r = results.get((ji, f), {})
            statuses[str(f)] = {**fold_status(art, f, r.get("rc"), r.get("killed", False)),
                                **{k: v for k, v in r.items() if k != "rc"}, "returncode": r.get("rc")}
        done = [f for f in job["folds"] if fold_done(art, f)]
        complete = bool(job["folds"]) and len(done) == len(job["folds"])
        if (ji, None) in results:  # DDP-style single command
            complete = results[(ji, None)]["rc"] == 0
        assembled = None
        if complete and job.get("assemble_cmd"):
            e = {k: v for k, v in env.items() if k != "KG_DEADLINE"}
            log("%s: all folds done: %s" % (job["name"], job["assemble_cmd"]))
            rc, _ = run_cmd(job["assemble_cmd"], e, logs / ("%s_assemble.log" % job["name"]),
                            "[asm %s] " % job["name"], T0 + budget_s - 120)
            assembled = rc == 0
        removed = 0
        for f in done:
            for base in {OUT / "artifacts" / job["name"], art}:
                r = base / ("fold%d_resume.pt" % f)
                if r.is_file():
                    r.unlink()
                    removed += 1
        errors = {str(f): tail(logs / ("%s_fold%d.log" % (job["name"], f))) for (j2, f), r in results.items()
                  if j2 == ji and f is not None and r.get("rc") not in (0, None)}
        if (ji, None) in results and results[(ji, None)]["rc"]:
            errors["all"] = tail(logs / "train.log")
        job_reports.append({
            "name": job["name"], "cmd": job["cmd"], "folds": job["folds"], "folds_done": done,
            "folds_incomplete": [f for f in job["folds"] if f not in done], "fold_status": statuses,
            "complete": complete, "assembled": assembled, "errors": errors, "resume_checkpoints_removed": removed,
        })
    for i, cmd in enumerate(cfg.get("post_cmds", [])):
        if time.time() < hard_deadline:
            run_cmd(cmd, env, logs / ("post%d.log" % i), "[post%d] " % i, hard_deadline)
    sampler.stop.set()

    # 4. outputs
    for d, ok in live.items():
        if not ok:
            copy_tree_missing(RUN / d, OUT / d)
    ledger = []
    lp = RUN / ".kaggle-gm" / "ledger.jsonl"
    if lp.is_file():
        (OUT / "kg_remote").mkdir(exist_ok=True)
        shutil.copy2(str(lp), str(OUT / "kg_remote" / "ledger.jsonl"))
        ledger = [json.loads(l) for l in lp.read_text(encoding="utf-8").splitlines() if l.strip()]
    all_status = [s for j in job_reports for s in j["fold_status"].values()]
    report = {
        "jobs": job_reports, "accelerator": cfg.get("accelerator"), "resource": resource, "gpus": gpus,
        "devices": devices,
        "started_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(T0)),
        "elapsed_s": round(time.time() - T0, 1), "budget_h": cfg["hours"],
        "deadline_hit": any(s.get("status") in ("timeout", "killed", "not-started") for s in all_status),
        "gpu_util": sampler.summary(), "ledger": ledger, "git_commit": cfg.get("git_commit"),
        "git_dirty": cfg.get("git_dirty"), "build_id": cfg.get("build_id"),
        "input_layout": cfg.get("input_layout"), "inputs": inputs,
    }
    (OUT / "kg_run.json").write_text(json.dumps(report, indent=1), encoding="utf-8")
    for j in job_reports:
        state = "complete" if j["complete"] else ("partial" if j["folds_done"] else "failed")
        log("KG_RUN_STATUS %s: %s | folds done %s | incomplete %s"
            % (j["name"], state, j["folds_done"], j["folds_incomplete"]))
        for f, txt in j["errors"].items():
            log("%s fold %s failed; last log lines:\n%s" % (j["name"], f, txt))
    if inputs_note:
        log(inputs_note + " (details at the start of this log and in kg_run.json)")
    log("session used %.2f %s-hours" % (report["elapsed_s"] / 3600, resource))


if __name__ == "__main__":
    main()
