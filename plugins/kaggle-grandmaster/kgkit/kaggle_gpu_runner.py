"""kaggle-grandmaster remote GPU/TPU training runner.

Generated by `python -m kgkit gpu build`, which embeds the run config and a zip of your code
(src/, kgkit, competition.json, and data/folds.csv packed column by column) below. Do not edit the
generated kernel: change the local code and rebuild, so local and remote runs stay identical.

What it does inside the Kaggle session:
  1. unpacks the code into a scratch dir and links every attached input into ./data (competition data
     always; datasets and kernel outputs there too, or each in its own folder such as
     ./data/ext/<slug>), so the training command runs with the same relative paths as on your
     machine. A name two inputs share is linked once, with a warning; ./artifacts and ./subs point
     into /kaggle/working (the saved output). ./data/folds.csv is written back from the packed split
     (or linked from the dataset given to --split-from) and checked against yours: the run stops
     before anything else when it differs;
  2. copies fold artefacts from `resume_sources` (a previous session's output) and skips folds that
     are already done;
  3. runs one process per (job, fold), one per GPU at a time (2x T4 = two folds, or two 1-fold
     screens of different ideas, in parallel for the same quota hour), or one per TPU chip (PJRT
     env: TPU_VISIBLE_CHIPS=<k> and single-chip process bounds), with KG_DEADLINE set so
     training checkpoints and exits before the session limit, and optional pruning against a
     baseline learning curve;
  4. for every job whose folds are all done, runs its assemble command once (it logs the
     experiment to the remote ledger and writes the submission);
  5. writes kg_run.json (fold statuses, timings, GPU utilisation, ledger records) for
     `python -m kgkit gpu collect`.

Standard library only. Prints ASCII only.
"""

