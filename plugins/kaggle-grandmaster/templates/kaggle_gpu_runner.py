"""kaggle-grandmaster remote GPU training runner.

Generated by `python -m kgkit gpu build`, which embeds the run config and a zip of your code
(src/, kgkit, competition.json, data/folds.csv) below. Do not edit the generated kernel: change the
local code and rebuild, so local and remote runs stay identical.

What it does inside the Kaggle session:
  1. unpacks the code into a scratch dir and links every attached input (competition data, your
     preprocessed datasets) into ./data, so the training command runs with the same relative paths
     as on your machine; ./artifacts and ./subs point into /kaggle/working (the saved output);
  2. copies fold artefacts from `resume_sources` (a previous session's output) and skips folds that
     are already done;
  3. runs one process per (job, fold), one per GPU at a time (2x T4 = two folds, or two 1-fold
     screens of different ideas, in parallel for the same quota hour), with KG_DEADLINE set so
     training checkpoints and exits before the session limit, and optional pruning against a
     baseline learning curve;
  4. for every job whose folds are all done, runs its assemble command once (it logs the
     experiment to the remote ledger and writes the submission);
  5. writes kg_run.json (fold statuses, timings, GPU utilisation, ledger records) for
     `python -m kgkit gpu collect`.

Standard library only. Prints ASCII only.
"""

import base64
import io
import json
import os
import shutil
import subprocess
import sys
import threading
import time
import zipfile
from pathlib import Path

CONFIG_B64 = "__KG_CONFIG_B64__"
PAYLOAD_B64 = "__KG_PAYLOAD_B64__"

T0 = time.time()
INPUT = Path(os.environ.get("KAGGLE_INPUT", "/kaggle/input"))
OUT = Path(os.environ.get("KAGGLE_WORKING", "/kaggle/working"))
RUN = Path(os.environ.get("KG_RUN_DIR", "/tmp/kgrun"))
WEIGHT_SUFFIXES = (".pt", ".pth", ".bin", ".ckpt", ".safetensors")


def log(msg):
    print("[kg %6.1fm] %s" % ((time.time() - T0) / 60, msg), flush=True)


# ----------------------------------------------------------------------------- inputs
def find_source(slug, max_depth=4):
    """Directory under INPUT named like the source slug (layouts differ between Kaggle image versions)."""
    name = slug.rstrip("/").split("/")[-1].lower()
    frontier = [INPUT]
    for _ in range(max_depth):
        nxt = []
        for d in frontier:
            try:
                kids = [k for k in d.iterdir() if k.is_dir()]
            except OSError:
                continue
            for k in kids:
                if k.name.lower() == name:
                    return k
            nxt.extend(kids)
        frontier = nxt
    return None


def link(src, dst):
    """Symlink (Kaggle/Linux); copy when symlinks are unavailable (Windows test runs)."""
    if dst.exists() or dst.is_symlink():
        return False
    try:
        os.symlink(str(src), str(dst), target_is_directory=src.is_dir())
    except (OSError, NotImplementedError):
        if src.is_dir():
            shutil.copytree(str(src), str(dst))
        else:
            shutil.copy2(str(src), str(dst))
    return True


def link_dir(dst, target):
    """Make dst a link to target (outputs are saved as they are written); returns False if it had to be a plain dir."""
    target.mkdir(parents=True, exist_ok=True)
    if dst.exists() or dst.is_symlink():
        return dst.resolve() == target.resolve()
    try:
        os.symlink(str(target), str(dst), target_is_directory=True)
        return True
    except (OSError, NotImplementedError):
        dst.mkdir(parents=True, exist_ok=True)
        return False


def copy_tree_missing(src, dst):
    n = 0
    for p in src.rglob("*"):
        if p.is_file():
            q = dst / p.relative_to(src)
            if not q.exists():
                q.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(str(p), str(q))
                n += 1
    return n


# ----------------------------------------------------------------------------- gpus
def list_gpus():
    fake = os.environ.get("KG_FAKE_GPUS")
    if fake is not None:
        return ["fake-gpu"] * int(fake)
    try:
        out = subprocess.run(["nvidia-smi", "--query-gpu=name,memory.total", "--format=csv,noheader"],
                             capture_output=True, text=True, timeout=30).stdout
        return [l.strip() for l in out.splitlines() if l.strip()]
    except (OSError, subprocess.SubprocessError):
        return []


class UtilSampler(threading.Thread):
    """Samples GPU utilisation; low mean utilisation means the run is input-bound (wasted quota)."""

    def __init__(self, interval):
        super().__init__(daemon=True)
        self.interval, self.samples, self.stop = interval, {}, threading.Event()

    def run(self):
        while not self.stop.wait(self.interval):
            try:
                out = subprocess.run(["nvidia-smi", "--query-gpu=index,utilization.gpu,memory.used",
                                      "--format=csv,noheader,nounits"], capture_output=True, text=True,
                                     timeout=20).stdout
            except (OSError, subprocess.SubprocessError):
                return
            for line in out.splitlines():
                parts = [p.strip() for p in line.split(",")]
                if len(parts) == 3 and parts[1].isdigit():
                    s = self.samples.setdefault(parts[0], {"util": [], "mem_mb": []})
                    s["util"].append(int(parts[1]))
                    s["mem_mb"].append(int(float(parts[2])))

    def summary(self):
        out = {}
        for idx, s in self.samples.items():
            if s["util"]:
                out[idx] = {"util_mean": round(sum(s["util"]) / len(s["util"]), 1),
                            "util_p10": sorted(s["util"])[len(s["util"]) // 10],
                            "mem_peak_mb": max(s["mem_mb"]), "n": len(s["util"])}
        return out


# ----------------------------------------------------------------------------- jobs
def stream(proc, logfile, prefix):
    with open(logfile, "a", encoding="utf-8", errors="replace") as f:
        for line in iter(proc.stdout.readline, ""):
            f.write(line)
            f.flush()
            sys.stdout.write(prefix + line.encode("ascii", "replace").decode("ascii"))
            sys.stdout.flush()


def run_cmd(cmd, env, logfile, prefix, hard_deadline):
    p = subprocess.Popen(cmd, shell=True, cwd=str(RUN), env=env, stdout=subprocess.PIPE,
                         stderr=subprocess.STDOUT, text=True, encoding="utf-8", errors="replace")
    t = threading.Thread(target=stream, args=(p, logfile, prefix), daemon=True)
    t.start()
    killed = False
    while p.poll() is None:
        if time.time() > hard_deadline:
            log("%s still running past the hard deadline: terminating so outputs are saved" % prefix.strip())
            p.terminate()
            try:
                p.wait(60)
            except subprocess.TimeoutExpired:
                p.kill()
            killed = True
            break
        time.sleep(2)
    t.join(30)
    return p.wait(), killed


def tail(path, n=40):
    try:
        return "".join(Path(path).read_text(encoding="utf-8", errors="replace").splitlines(True)[-n:])
    except OSError:
        return ""


def fold_done(art, f):
    st = art / ("fold%d_status.json" % f)
    if st.is_file():
        try:
            return json.loads(st.read_text(encoding="utf-8")).get("status") == "done"
        except ValueError:
            pass
    return (art / ("fold%d_oof.npy" % f)).is_file()


def fold_status(art, f, rc=None, killed=False):
    st = art / ("fold%d_status.json" % f)
    if st.is_file():
        try:
            return json.loads(st.read_text(encoding="utf-8"))
        except ValueError:
            pass
    if (art / ("fold%d_oof.npy" % f)).is_file():
        return {"fold": f, "status": "done"}
    if killed:
        return {"fold": f, "status": "killed"}
    if rc is None:
        return {"fold": f, "status": "not-started"}
    return {"fold": f, "status": "failed" if rc else "unknown", "returncode": rc}


# ----------------------------------------------------------------------------- main
def main():
    cfg = json.loads(base64.b64decode(CONFIG_B64).decode("utf-8"))
    jobs = cfg["jobs"]
    budget_s = float(cfg["hours"]) * 3600
    safety_s = max(600.0, 0.08 * budget_s)
    deadline = T0 + budget_s - safety_s              # training must have checkpointed by now
    hard_deadline = T0 + budget_s - 0.4 * safety_s   # processes still alive are terminated here
    gpus = list_gpus()
    log("jobs %s | accelerator %s | gpus: %s | budget %.2fh (graceful stop at %.2fh)"
        % ([j["name"] for j in jobs], cfg.get("accelerator"), gpus or "NONE", budget_s / 3600, (deadline - T0) / 3600))
    if not gpus and not cfg.get("allow_cpu"):
        log("WARNING: no GPU visible - check the kernel accelerator setting; training on CPU")

    # 1. code + data
    if RUN.exists():
        shutil.rmtree(str(RUN))
    RUN.mkdir(parents=True)
    zipfile.ZipFile(io.BytesIO(base64.b64decode(PAYLOAD_B64))).extractall(str(RUN))
    (RUN / "data").mkdir(exist_ok=True)
    for slug in cfg.get("sources", []):
        src = find_source(slug)
        if src is None:
            log("WARNING: input source %s not found under %s" % (slug, INPUT))
            continue
        n = sum(link(k, RUN / "data" / k.name) for k in sorted(src.iterdir()))
        log("linked %d entries of %s into data/" % (n, src))
    OUT.mkdir(parents=True, exist_ok=True)
    live = {d: link_dir(RUN / d, OUT / d) for d in ("artifacts", "subs")}
    arts = {}
    for job in jobs:
        art = arts[job["name"]] = RUN / "artifacts" / job["name"]
        art.mkdir(parents=True, exist_ok=True)
        for slug in cfg.get("resume_sources", []):
            src = find_source(slug)
            prev = src / "artifacts" / job["name"] if src else None
            if prev is not None and prev.is_dir():
                log("resume %s: copied %d files from %s" % (job["name"], copy_tree_missing(prev, art), prev))
    if cfg.get("pip"):
        extra = []
        for w in [find_source(s) for s in cfg.get("wheel_sources", [])]:
            if w is not None:
                extra += ["--no-index", "--find-links", str(w)]
        log("pip install %s" % " ".join(cfg["pip"]))
        subprocess.run([sys.executable, "-m", "pip", "install", "-q", *extra, *cfg["pip"]], check=False)

    env = dict(os.environ, PYTHONPATH=os.pathsep.join([str(RUN), os.environ.get("PYTHONPATH", "")]),
               KGKIT_HOME=str(RUN), PYTHONUNBUFFERED="1", KG_DEADLINE=str(deadline),
               KG_RESERVE_S=str(cfg.get("reserve_s", 600)))
    prune = cfg.get("prune")
    if prune and (RUN / "_kg" / "baseline").is_dir():
        env.update(KG_PRUNE_BASELINE=str(RUN / "_kg" / "baseline"), KG_PRUNE_MARGIN=str(prune["margin"]),
                   KG_PRUNE_MIN_FRAC=str(prune.get("min_frac", 0.3)))
        log("pruning against %s (margin %s)" % (prune.get("baseline"), prune["margin"]))
    logs = OUT / "logs"
    logs.mkdir(exist_ok=True)
    sampler = UtilSampler(float(os.environ.get("KG_SAMPLE_S", "30")))
    if gpus and "KG_FAKE_GPUS" not in os.environ:
        sampler.start()

    # 2. tasks = (job, fold); one process per task, one task per GPU at a time. Interleaved by fold so
    #    two screens (or two folds of one job) keep both T4s busy.
    results = {}
    if len(jobs) == 1 and "{fold}" not in jobs[0]["cmd"]:  # a command that drives the GPUs itself (DDP)
        t = time.time()
        rc, killed = run_cmd(jobs[0]["cmd"], env, logs / "train.log", "[train] ", hard_deadline)
        results[(0, None)] = {"rc": rc, "killed": killed, "seconds": round(time.time() - t, 1)}
    else:
        todo = []
        for f in sorted({f for j in jobs for f in j["folds"]}):
            for ji, job in enumerate(jobs):
                if f in job["folds"]:
                    if fold_done(arts[job["name"]], f):
                        log("%s fold %d already done (resumed)" % (job["name"], f))
                    else:
                        todo.append((ji, f))
        lock = threading.Lock()

        def worker(slot):
            while True:
                with lock:
                    if not todo:
                        return
                    ji, f = todo.pop(0)
                job = jobs[ji]
                tag = "%s/f%d" % (job["name"], f)
                if time.time() > deadline - float(cfg.get("min_fold_start_s", 600)):
                    results[(ji, f)] = {"rc": None, "seconds": 0, "note": "not started: no time left"}
                    continue
                e = dict(env, KG_DEFER_ASSEMBLE="1")  # parallel folds must not race to log the experiment
                if gpus:
                    e["CUDA_VISIBLE_DEVICES"] = str(slot)
                cmd = job["cmd"].replace("{fold}", str(f))
                log("%s -> gpu %s: %s" % (tag, slot if gpus else "cpu", cmd))
                t = time.time()
                rc, killed = run_cmd(cmd, e, logs / ("%s_fold%d.log" % (job["name"], f)), "[%s] " % tag,
                                     hard_deadline)
                results[(ji, f)] = {"rc": rc, "killed": killed, "seconds": round(time.time() - t, 1), "gpu": slot}
                log("%s finished rc=%s in %.1f min" % (tag, rc, (time.time() - t) / 60))

        n_workers = max(1, min(len(gpus) or 1, len(todo) or 1))
        threads = [threading.Thread(target=worker, args=(i,)) for i in range(n_workers)]
        for t in threads:
            t.start()
        for t in threads:
            t.join()

    # 3. per-job status; assemble each job whose folds are all done
    job_reports = []
    for ji, job in enumerate(jobs):
        art, statuses = arts[job["name"]], {}
        for f in job["folds"]:
            r = results.get((ji, f), {})
            statuses[str(f)] = {**fold_status(art, f, r.get("rc"), r.get("killed", False)),
                                **{k: v for k, v in r.items() if k != "rc"}, "returncode": r.get("rc")}
        done = [f for f in job["folds"] if fold_done(art, f)]
        complete = bool(job["folds"]) and len(done) == len(job["folds"])
        if (ji, None) in results:  # DDP-style single command
            complete = results[(ji, None)]["rc"] == 0
        assembled = None
        if complete and job.get("assemble_cmd"):
            e = {k: v for k, v in env.items() if k != "KG_DEADLINE"}
            log("%s: all folds done: %s" % (job["name"], job["assemble_cmd"]))
            rc, _ = run_cmd(job["assemble_cmd"], e, logs / ("%s_assemble.log" % job["name"]),
                            "[asm %s] " % job["name"], T0 + budget_s - 120)
            assembled = rc == 0
        removed = 0
        for f in done:
            for base in {OUT / "artifacts" / job["name"], art}:
                r = base / ("fold%d_resume.pt" % f)
                if r.is_file():
                    r.unlink()
                    removed += 1
        errors = {str(f): tail(logs / ("%s_fold%d.log" % (job["name"], f))) for (j2, f), r in results.items()
                  if j2 == ji and f is not None and r.get("rc") not in (0, None)}
        if (ji, None) in results and results[(ji, None)]["rc"]:
            errors["all"] = tail(logs / "train.log")
        job_reports.append({
            "name": job["name"], "cmd": job["cmd"], "folds": job["folds"], "folds_done": done,
            "folds_incomplete": [f for f in job["folds"] if f not in done], "fold_status": statuses,
            "complete": complete, "assembled": assembled, "errors": errors, "resume_checkpoints_removed": removed,
        })
    for i, cmd in enumerate(cfg.get("post_cmds", [])):
        if time.time() < hard_deadline:
            run_cmd(cmd, env, logs / ("post%d.log" % i), "[post%d] " % i, hard_deadline)
    sampler.stop.set()

    # 4. outputs
    for d, ok in live.items():
        if not ok:
            copy_tree_missing(RUN / d, OUT / d)
    ledger = []
    lp = RUN / ".kaggle-gm" / "ledger.jsonl"
    if lp.is_file():
        (OUT / "kg_remote").mkdir(exist_ok=True)
        shutil.copy2(str(lp), str(OUT / "kg_remote" / "ledger.jsonl"))
        ledger = [json.loads(l) for l in lp.read_text(encoding="utf-8").splitlines() if l.strip()]
    all_status = [s for j in job_reports for s in j["fold_status"].values()]
    report = {
        "jobs": job_reports, "accelerator": cfg.get("accelerator"), "gpus": gpus,
        "started_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(T0)),
        "elapsed_s": round(time.time() - T0, 1), "budget_h": cfg["hours"],
        "deadline_hit": any(s.get("status") in ("timeout", "killed", "not-started") for s in all_status),
        "gpu_util": sampler.summary(), "ledger": ledger, "git_commit": cfg.get("git_commit"),
        "git_dirty": cfg.get("git_dirty"), "build_id": cfg.get("build_id"),
    }
    (OUT / "kg_run.json").write_text(json.dumps(report, indent=1), encoding="utf-8")
    for j in job_reports:
        state = "complete" if j["complete"] else ("partial" if j["folds_done"] else "failed")
        log("KG_RUN_STATUS %s: %s | folds done %s | incomplete %s"
            % (j["name"], state, j["folds_done"], j["folds_incomplete"]))
        for f, txt in j["errors"].items():
            log("%s fold %s failed; last log lines:\n%s" % (j["name"], f, txt))
    log("session used %.2f GPU-hours" % (report["elapsed_s"] / 3600))


if __name__ == "__main__":
    main()
